def test_garbage_before_valid_frame():
    frames = P.parse_one(b"\xDE\xAD\xBE\xEF" + GOLDEN_STOP_8)
    assert len(frames) == 1
    assert frames[0].type == P.TYPE_STOP
    assert frames[0].seq == 0x08


def test_garbage_with_fake_header_resyncs_one_byte_at_a_time():
    # A stray 0x5A with an impossible len must only cost one byte.
    frames = P.parse_one(b"\x5A\x00\x13" + GOLDEN_STOP_8)
    assert len(frames) == 1
    assert frames[0].type == P.TYPE_STOP
    assert frames[0].raw == GOLDEN_STOP_8


def test_bad_crc_costs_one_byte_and_recovers():
    bad = bytearray(GOLDEN_SET_VELOCITY_300)
    bad[-1] ^= 0xFF
    frames = P.parse_one(bytes(bad) + GOLDEN_STOP_8)
    assert [f.type for f in frames] == [P.TYPE_STOP]
    assert frames[0].raw == GOLDEN_STOP_8


@pytest.mark.parametrize("split", list(range(1, len(GOLDEN_SET_VELOCITY_300))))
def test_valid_frame_split_at_every_byte_boundary(split):
    raw = GOLDEN_SET_VELOCITY_300
    parser = P.FrameParser()
    first = parser.feed(raw[:split], 0.0)
    second = parser.feed(raw[split:], 0.001)
    frames = first + second
    assert len(frames) == 1, "split at %d produced %r" % (split, frames)
    assert frames[0].raw == raw
    assert frames[0].type == P.TYPE_SET_VELOCITY
    assert frames[0].seq == 0x10


def test_two_frames_concatenated():
    frames = P.parse_one(GOLDEN_SET_VELOCITY_300 + GOLDEN_STOP_8)
    assert [f.type for f in frames] == [P.TYPE_SET_VELOCITY, P.TYPE_STOP]
    assert [f.seq for f in frames] == [0x10, 0x08]


def test_partial_frame_timeout_clears_buffer():
    parser = P.FrameParser()
    parser.feed(GOLDEN_SET_VELOCITY_300[:8], 0.0)
    assert parser.buffered == 8

    # 49 ms without a byte: still waiting.
    assert parser.tick(0.049) is False
    assert parser.buffered == 8

    # More than 50 ms without a byte: half frame dropped.
    assert parser.tick(0.051) is True
    assert parser.buffered == 0

    # ... and a fresh frame is still accepted afterwards.
    assert len(parser.feed(GOLDEN_STOP_8, 0.060)) == 1


def test_slow_frame_is_accepted_no_whole_frame_timeout():
    # §2.5: the timeout is between *bytes*, not from the start of the frame.
    parser = P.FrameParser()
    frames = []
    for index, value in enumerate(GOLDEN_SET_VELOCITY_300):
        now = index * 0.049
        frames.extend(parser.feed(bytes((value,)), now))
        assert parser.tick(now + 0.049) is False
    assert len(frames) == 1
    assert frames[0].raw == GOLDEN_SET_VELOCITY_300


def test_partial_frame_dropped_when_stream_stalls_mid_frame():
    parser = P.FrameParser()
    assert parser.feed(GOLDEN_SET_VELOCITY_300[:4], 1.0) == []
    assert parser.buffered == 4
    assert parser.tick(1.051) is True
    assert parser.buffered == 0


