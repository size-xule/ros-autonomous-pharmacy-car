def test_golden_telemetry_decodes_all_fields():
    frame = P.parse_one(GOLDEN_TELEMETRY)[0]
    telemetry = P.decode_telemetry(frame.payload)
    assert isinstance(P.decode_frame(frame), P.Telemetry)

    assert telemetry.vx_mm_s == 500
    assert telemetry.vx_mps == pytest.approx(0.5)
    assert telemetry.yaw_cdeg == -1234
    assert telemetry.yaw_deg == pytest.approx(-12.34)
    assert telemetry.gyro_cdps == 123
    assert telemetry.gyro_dps == pytest.approx(1.23)
    assert (telemetry.pwm_left, telemetry.pwm_right) == (230, 230)
    assert telemetry.steer_us == 1500
    assert telemetry.battery_mv == 11800

    assert telemetry.flags.raw == 0x11
    assert telemetry.flags.armed is True
    assert telemetry.flags.gyro_fs_ok is True
    assert telemetry.flags.fault is False
    assert telemetry.flags.imu_ok is False
    assert telemetry.flags.names() == ["ARMED", "GYRO_FS_OK"]
    assert str(telemetry.flags) == "ARMED|GYRO_FS_OK"

    assert telemetry.age_ms == 0
    assert telemetry.age_valid is True
    # IMU_OK is clear in this vector, so yaw must not be trusted for odometry.
    assert telemetry.imu_trusted is False


def test_telemetry_age_255_marks_snapshot_invalid():
    payload = struct.pack(">hhhhhHHBB", 0, 0, 0, 0, 0, 1500, 12000, 0x09, 255)
    telemetry = P.decode_telemetry(payload)
    assert telemetry.age_ms == P.AGE_INVALID
    assert telemetry.age_valid is False
    assert telemetry.imu_trusted is False


