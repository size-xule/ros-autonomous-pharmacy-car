# §4.4 IMU_RAW decoder (constructed 39-byte frame)
# ---------------------------------------------------------------------------


def test_imu_raw_decode():
    status = P.ST_OK
    gyro = (123456, -654321, 1000)          # 1e-5 dps
    accel = (-1000, 2000, 9800)             # 1e-4 mm/s^2
    quat = (10000, 0, 0, 0)                 # w, x, y, z, 1/10000

    payload = (
        struct.pack(">B", status)
        + struct.pack(">3i", *gyro)
        + struct.pack(">3i", *accel)
        + struct.pack(">4h", *quat)
    )
    assert len(payload) == 33

    raw = P.build_frame(P.TYPE_IMU_RAW, 0x21, payload)
    assert len(raw) == 39

    frames = P.parse_one(raw)
    assert len(frames) == 1
    assert frames[0].type == P.TYPE_IMU_RAW
    assert len(frames[0].raw) == 39

    imu = P.decode_imu_raw(frames[0].payload)
    assert imu.status == P.ST_OK
    assert imu.gyro_dps == pytest.approx((1.23456, -6.54321, 0.01))
    assert imu.accel_mm_s2 == pytest.approx((-0.1, 0.2, 0.98))
    assert imu.quaternion == pytest.approx((1.0, 0.0, 0.0, 0.0))
    assert P.decode_frame(frames[0]) == imu


def test_imu_raw_stale_status_with_zero_payload():
    payload = bytes(33)
    payload = bytes((P.ST_STALE,)) + payload[1:]
    imu = P.decode_imu_raw(payload)
    assert imu.status == P.ST_STALE
    assert imu.gyro_dps == (0.0, 0.0, 0.0)
    assert imu.quaternion == (0.0, 0.0, 0.0, 0.0)


def test_decode_imu_raw_rejects_wrong_payload_length():
    with pytest.raises(P.ProtocolError):
        P.decode_imu_raw(b"\x00" * 32)


