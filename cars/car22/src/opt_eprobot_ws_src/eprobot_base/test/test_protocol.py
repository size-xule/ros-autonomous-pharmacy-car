@pytest.mark.parametrize("total", [6, 7, 10, 72])
def test_unknown_type_with_legal_length_is_accepted(total):
    raw = make_frame(0x7F, 0x01, b"\x00" * (total - 6))
    frames = P.parse_one(raw)
    assert len(frames) == 1
    assert frames[0].type == 0x7F
    assert len(frames[0].raw) == total
    # It is a legal *frame*, but not a data frame the driver knows.
    assert P.decode_frame(frames[0]) is None


def test_unknown_type_with_illegal_length_is_rejected():
    for total in (5, 73):
        raw = bytes((HEADER, total, 0x7F, 0x01))
        assert P.parse_one(raw) == [], "len=%d must be rejected" % total


def test_len_seven_uplink_is_an_ack_not_a_data_frame():
    # PROTOCOL.md §3.6: "任何 bit7=1、len=7 的帧都按通用 ACK 解析；同一 type
    # 的合法数据帧仍按表里的长度解析。实现上不要为了表驱动把 len=7 的应答
    # 丢掉。"  This includes 0xC0/0x91/0x92, whose table length is 22/39/70:
    # a mis-sent 0x91 request is answered with a 0x91 len=7 ACK, and the
    # parser must hand that ACK to the client instead of table-rejecting it.
    #
    # Regression: the parser used to check TYPE_LEN before the len==7 ACK
    # exception and silently dropped these legal frames.
    for type_ in (P.TYPE_TELEMETRY, P.TYPE_IMU_RAW, P.TYPE_DIAG):
        ack = make_frame(type_, 0x05, b"\x01")
        frames = P.parse_one(ack)
        assert len(frames) == 1, (
            "PROTOCOL.md §3.6 requires every bit7=1, len=7 frame to be "
            "accepted as a generic ACK, but the parser dropped the 7-byte "
            "0x%02X frame (TYPE_LEN says %d)." % (type_, P.TYPE_LEN[type_])
        )
        frame = frames[0]
        assert frame.type == type_
        assert len(frame.raw) == 7
        assert frame.status == P.ST_UNKNOWN_CMD
        assert frame.ack_for == (type_ & 0x7F)
        assert P.decode_frame(frame) is None


def test_ack_for_is_none_for_downlink_frames():
    frame = P.parse_one(GOLDEN_SET_VELOCITY_300)[0]
    assert frame.ack_for is None
    assert frame.status is None


