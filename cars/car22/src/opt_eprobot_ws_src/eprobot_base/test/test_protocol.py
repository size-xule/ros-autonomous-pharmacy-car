# §4.5 DIAG decoder (constructed 70-byte frame)
# ---------------------------------------------------------------------------


def test_diag_decode():
    raw_accel = (101, -202, 303)            # LSB
    raw_gyro = (11, -22, 33)                # LSB
    accel_phys = (1000, -2000, 3000)        # 0.01 mm/s^2
    gyro_phys = (100, -200, 300)            # 0.01 dps
    quat = (10000, -5000, 2500, 1250)       # 1/10000
    euler = (100, -200, 1234)               # 0.01 deg
    flags = P.FLAG_ARMED | P.FLAG_IMU_OK | P.FLAG_GYRO_FS_OK
    dt_ticks = 1680
    i2c_errors = 7

    payload = (
        struct.pack(">B", P.ST_OK)
        + struct.pack(">3h", *raw_accel)
        + struct.pack(">3h", *raw_gyro)
        + struct.pack(">3i", *accel_phys)
        + struct.pack(">3i", *gyro_phys)
        + struct.pack(">4i", *quat)
        + struct.pack(">3h", *euler)
        + struct.pack(">B", flags)
        + struct.pack(">H", dt_ticks)
        + struct.pack(">H", i2c_errors)
    )
    assert len(payload) == 64

    raw = P.build_frame(P.TYPE_DIAG, 0x22, payload)
    assert len(raw) == 70

    frames = P.parse_one(raw)
    assert len(frames) == 1
    assert frames[0].type == P.TYPE_DIAG
    assert len(frames[0].raw) == 70

    diag = P.decode_diag(frames[0].payload)
    assert diag.status == P.ST_OK
    assert diag.raw_accel == raw_accel
    assert diag.raw_gyro == raw_gyro
    assert diag.accel_mm_s2 == pytest.approx((10.0, -20.0, 30.0))
    assert diag.gyro_dps == pytest.approx((1.0, -2.0, 3.0))
    assert diag.quaternion == pytest.approx((1.0, -0.5, 0.25, 0.125))
    assert diag.euler_deg == pytest.approx((1.0, -2.0, 12.34))
    assert diag.flags.raw == flags
    assert diag.flags.armed and diag.flags.imu_ok and diag.flags.gyro_fs_ok
    assert diag.dt_ticks == 1680
    assert diag.i2c_errors == 7
    assert P.decode_frame(frames[0]) == diag


def test_decode_diag_rejects_wrong_payload_length():
    with pytest.raises(P.ProtocolError):
        P.decode_diag(b"\x00" * 63)


