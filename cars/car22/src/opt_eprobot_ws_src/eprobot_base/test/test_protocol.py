# §7.1 golden vectors (spec bytes, hard-coded)
# ---------------------------------------------------------------------------

GOLDEN_CRC_INPUT = b"123456789"
GOLDEN_CRC = 0x29B1

GOLDEN_SET_VELOCITY_HOLD = bytes.fromhex(
    "5A 10 01 07 01 F4 00 00 FF FF FF FF FF FF 15 EB"
)
GOLDEN_ACK_SET_VELOCITY_7 = bytes.fromhex("5A 07 81 07 00 86 40")
GOLDEN_SET_VELOCITY_300 = bytes.fromhex(
    "5A 10 01 10 01 2C 00 32 00 23 00 05 00 00 50 26"
)
GOLDEN_ACK_SET_VELOCITY_16 = bytes.fromhex("5A 07 81 10 00 1C A4")
GOLDEN_STOP_8 = bytes.fromhex("5A 06 02 08 CC 9A")
GOLDEN_ACK_STOP_8 = bytes.fromhex("5A 07 82 08 00 CF 2E")
GOLDEN_TELEMETRY = bytes.fromhex(
    "5A 16 C0 2A 01 F4 FB 2E 00 7B 00 E6 00 E6 05 DC 2E 18 11 00 A7 4A"
)
GOLDEN_GET_DIAG_9 = bytes.fromhex("5A 06 12 09 DF C8")
GOLDEN_UNKNOWN_7E = bytes.fromhex("5A 06 7E 33 06 96")
GOLDEN_ACK_UNKNOWN_7E = bytes.fromhex("5A 07 FE 33 01 AB 09")


def test_crc16_self_check():
    assert P.crc16(GOLDEN_CRC_INPUT) == GOLDEN_CRC


def test_crc16_empty_is_init_value():
    assert P.crc16(b"") == 0xFFFF


def test_crc16_is_big_endian_in_frames():
    # The last two bytes of every golden frame are the big-endian CRC of the
    # preceding bytes (§2.3, §2.4).
    for raw in (
        GOLDEN_SET_VELOCITY_HOLD,
        GOLDEN_SET_VELOCITY_300,
        GOLDEN_STOP_8,
        GOLDEN_TELEMETRY,
        GOLDEN_GET_DIAG_9,
        GOLDEN_UNKNOWN_7E,
        GOLDEN_ACK_UNKNOWN_7E,
    ):
        assert P.crc16(raw[:-2]) == (raw[-2] << 8) | raw[-1], raw.hex()


def test_golden_set_velocity_hold():
    frame = P.encode_set_velocity(500, 0, 0x07, kp=-1, ki=-1, kd=-1)
    assert frame == GOLDEN_SET_VELOCITY_HOLD
    assert len(frame) == 16
    assert frame[:4] == bytes((0x5A, 0x10, 0x01, 0x07))


def test_golden_set_velocity_ack_parses():
    frames = P.parse_one(GOLDEN_ACK_SET_VELOCITY_7)
    assert len(frames) == 1
    frame = frames[0]
    assert frame.type == 0x81
    assert frame.type == P.TYPE_ACK_SET_VELOCITY
    assert frame.seq == 0x07
    assert len(frame.raw) == 7
    assert frame.payload == b"\x00"
    assert frame.status == 0
    assert frame.ack_for == P.TYPE_SET_VELOCITY


def test_golden_set_velocity_300():
    frame = P.encode_set_velocity(300, 50, 0x10, kp=35, ki=5, kd=0)
    assert frame == GOLDEN_SET_VELOCITY_300
    vx, delta, kp, ki, kd = struct.unpack(">hhhhh", frame[4:-2])
    assert (vx, delta, kp, ki, kd) == (300, 50, 35, 5, 0)


def test_golden_set_velocity_ack_16():
    assert P.build_frame(P.TYPE_ACK_SET_VELOCITY, 0x10, b"\x00") == (
        GOLDEN_ACK_SET_VELOCITY_16
    )


def test_golden_stop_and_ack():
    assert P.encode_stop(0x08) == GOLDEN_STOP_8
    assert P.build_frame(P.TYPE_ACK_STOP, 0x08, b"\x00") == GOLDEN_ACK_STOP_8
    frame = P.parse_one(GOLDEN_ACK_STOP_8)[0]
    assert (frame.type, frame.seq, frame.status) == (0x82, 0x08, 0)


def test_golden_get_diag():
    assert P.encode_get_diag(0x09) == GOLDEN_GET_DIAG_9


def test_golden_unknown_request_and_ack():
    assert make_frame(0x7E, 0x33) == GOLDEN_UNKNOWN_7E
    ack = P.build_unknown_ack(0xFE, 0x33)
    assert ack == GOLDEN_ACK_UNKNOWN_7E

    frame = P.parse_one(ack)[0]
    assert frame.type == 0xFE
    assert len(frame.raw) == 7
    assert frame.seq == 0x33
    assert frame.payload == b"\x01"
    assert frame.status == P.ST_UNKNOWN_CMD
    assert frame.ack_for == 0x7E


def test_golden_telemetry_parses():
    frames = P.parse_one(GOLDEN_TELEMETRY)
    assert len(frames) == 1
    frame = frames[0]
    assert frame.type == P.TYPE_TELEMETRY
    assert frame.seq == 0x2A
    assert len(frame.raw) == 22
    assert len(frame.payload) == 16


# ---------------------------------------------------------------------------
# §7.2 negative vectors: zero frames, nothing buffered, no answer possible
# ---------------------------------------------------------------------------

NEGATIVE_VECTORS = [
    (
        "N1_crc_error",
        "5A 10 01 10 01 2C 00 32 00 23 00 05 00 00 50 D9",
    ),
    (
        "N2_len_out_of_range",
        "5A 4C 01 12 01 2C 00 32 00 23 00 05 00 00",
    ),
    (
        "N3_len_type_mismatch",
        "5A 10 02 13 00 00 00 00 00 00 00 00 00 00 64 12",
    ),
]


@pytest.mark.parametrize("name,hexstr", NEGATIVE_VECTORS, ids=[n for n, _ in NEGATIVE_VECTORS])
def test_negative_vectors_produce_no_frames(name, hexstr):
    raw = bytes.fromhex(hexstr)
    parser = P.FrameParser()
    frames = parser.feed(raw, 0.0)
    assert frames == [], "%s must be silently discarded, got %r" % (name, frames)
    assert parser.buffered == 0, "%s left %d bytes stuck in the parser" % (
        name,
        parser.buffered,
    )


def test_n1_is_only_a_crc_error():
    raw = bytes.fromhex(NEGATIVE_VECTORS[0][1])
    assert raw[1] == 16 and raw[2] == P.TYPE_SET_VELOCITY  # len/type are fine
    assert P.crc16(raw[:-2]) != (raw[-2] << 8) | raw[-1]
    parser = P.FrameParser()
    parser.feed(raw, 0.0)
    assert parser.crc_errors == 1
    assert parser.length_errors == 0


def test_n2_len_is_checked_before_waiting_for_bytes():
    raw = bytes.fromhex(NEGATIVE_VECTORS[1][1])
    assert raw[1] == 0x4C and raw[1] > P.FRAME_MAX
    parser = P.FrameParser()
    # Only the four header bytes are needed to reject len=76; the rest of the
    # vector must not be required before resynchronising.
    frames = parser.feed(raw[:4], 0.0)
    assert frames == []
    assert parser.length_errors == 1


def test_n3_crc_is_valid_so_length_table_must_reject_it():
    raw = bytes.fromhex(NEGATIVE_VECTORS[2][1])
    assert raw[2] == P.TYPE_STOP and raw[1] == 16  # STOP declared as 16 bytes
    assert P.crc16(raw[:-2]) == (raw[-2] << 8) | raw[-1]  # CRC itself is good
    parser = P.FrameParser()
    assert parser.feed(raw, 0.0) == []
    assert parser.length_errors >= 1


