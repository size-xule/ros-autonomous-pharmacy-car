"""Wire-protocol tests for ``eprobot_base.protocol`` (PROTOCOL.md v2.1).

Covers the byte-for-byte golden vectors of PROTOCOL.md §7.1, the negative
vectors of §7.2 (silent discard), the streaming-parser rules of §2.5 and the
uplink decoders of §4.2/§4.4/§4.5.

The frame bytes in ``GOLDEN_*`` are copied from the specification, never
generated by the implementation under test.
"""

import struct

import pytest

from eprobot_base import protocol as P

HEADER = 0x5A


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def make_frame(type_, seq, payload=b""):
    """Assemble a frame the way PROTOCOL.md §2.1 describes.

    Used for frames whose type is not in the length table (``build_frame``
    refuses those by design).  The layout is written out explicitly here so the
    parser tests do not simply mirror the implementation.
    """
    total = len(payload) + 6
    assert 6 <= total <= 72
    body = bytes((HEADER, total, type_, seq)) + payload
    crc = P.crc16(body)
    return body + bytes((crc >> 8, crc & 0xFF))


