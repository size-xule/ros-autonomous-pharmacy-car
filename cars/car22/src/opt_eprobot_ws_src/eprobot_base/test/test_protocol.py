# regression: consecutive-CRC counter (review M6, PROTOCOL.md 6.1)
# ---------------------------------------------------------------------------


def test_consecutive_crc_errors_reset_on_valid_frame():
    bad = bytearray(GOLDEN_TELEMETRY)
    bad[-1] ^= 0xFF

    parser = P.FrameParser()
    assert parser.feed(bytes(bad), 0.0) == []
    assert parser.crc_errors == 1
    assert parser.consecutive_crc_errors == 1

    # A valid frame resets the consecutive counter but not the cumulative one.
    frames = parser.feed(GOLDEN_STOP_8, 0.01)
    assert [f.type for f in frames] == [P.TYPE_STOP]
    assert parser.consecutive_crc_errors == 0
    assert parser.crc_errors == 1
